/**
 * 智能体向作者提问的通道。
 *
 * 设定官与执笔者都有拿不准的时候：作者的意图含糊、素材里没有关键事实、
 * 这一章该走哪条路说不准。硬猜一个答案写下去，错的不是这一句而是整章。
 * 与其猜，不如停下来问一句。
 *
 * 提问工具的形状与别的工具不同：它不立刻返回，而是挂在那里等作者作答，
 * 答案到手后作为工具结果回到对话里，智能体在同一轮里接着往下做。
 * 这条通道就是那根"挂着等"的线。
 */
export interface AskRequest {
	/** 问什么。一句话，具体到作者能一句话答上来。 */
	question: string;
	/** 可选的候选答案，给作者点选用；没有几种明确选择就别给。 */
	options?: string[];
}

/**
 * 提问通道。
 *
 * 拿不到实现时（没有提问通道的场合），工具压根不出现 ——
 * 给模型一个问不出去的工具，比不给更糟。
 */
export interface AskBroker {
	/**
	 * 提出一个问题，等作者回答。
	 *
	 * 返回作者的原话。作者跳过、没看到、超时或这一轮被中止时返回空串，
	 * 工具据此告诉模型"没答上"，模型按自己的判断继续，不要编造作者的回答。
	 */
	ask(request: AskRequest, signal?: AbortSignal): Promise<string>;
}
